export type TypoPassage = {
  chars: string[]; // 화면에 보여 줄 글자(오타 포함), 글자 하나가 누르는 단위
  typoAt: number[]; // 오타 글자의 위치
  correct: string; // 오타 없는 원문 (기록용)
};

// "{정답|오타}" 표기를 풀어 보여 줄 글자 배열과 오타 위치를 만듭니다.
export function parsePassage(source: string): TypoPassage {
  const chars: string[] = [];
  const typoAt: number[] = [];
  let correct = "";
  const re = /\{(.)\|(.)\}/g;
  let last = 0;
  for (const m of source.matchAll(re)) {
    for (const ch of source.slice(last, m.index)) {
      chars.push(ch);
      correct += ch;
    }
    typoAt.push(chars.length);
    chars.push(m[2]);
    correct += m[1];
    last = m.index + m[0].length;
  }
  for (const ch of source.slice(last)) {
    chars.push(ch);
    correct += ch;
  }
  return { chars, typoAt, correct };
}

export const TYPO_PASSAGES: TypoPassage[] = TYPO_SOURCES.map(parsePassage);

// 세 조건에서 같은 지문이 다시 나오지 않도록 지문을 세트 3개로 나눕니다(번갈아 배정, 각 20개).
export const TYPO_SET_COUNT = 3;
export const TYPO_SETS: number[][] = Array.from({ length: TYPO_SET_COUNT }, (_, k) => TYPO_PASSAGES.map((_, i) => i).filter((i) => i % TYPO_SET_COUNT === k));

// k번째 조건(0부터)에 쓸 세트 = k. 설계 문서 3절 "문제 세트는 항상 1→2→3 순서": 조건 순서가 라틴 방격으로 돌아가므로 세트와 조건이 같은 횟수로 만납니다.
export const setFor = (position: number) => position % TYPO_SET_COUNT;

// 지문 순서를 시드로 섞습니다. setIndex 를 주면 그 세트의 지문만, 없으면 전체(과제 후보 시험용). 바닥나면 처음부터 다시 돕니다(기록에 회차가 남음).
export function passageOrder(rand: () => number, setIndex?: number): number[] {
  const order = setIndex === undefined ? TYPO_PASSAGES.map((_, i) => i) : [...TYPO_SETS[setIndex]];
  for (let i = order.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [order[i], order[j]] = [order[j], order[i]];
  }
  return order;
}

export type TypoScore = {
  hits: number;
  misses: number;
  falseMarks: number;
  missed: string; // 놓친 오타를 "원문→오타" 꼴로 (예: "졌→젔")
  wrong: string; // 잘못 누른 글자
};

export function scoreTypo(passage: TypoPassage, marked: Set<number>): TypoScore {
  const correctChars = [...passage.correct];
  const hitAt = passage.typoAt.filter((i) => marked.has(i));
  const missedAt = passage.typoAt.filter((i) => !marked.has(i));
  const wrongAt = [...marked].filter((i) => !passage.typoAt.includes(i)).sort((x, y) => x - y);
  return {
    hits: hitAt.length,
    misses: missedAt.length,
    falseMarks: wrongAt.length,
    missed: missedAt.map((i) => `${correctChars[i]}→${passage.chars[i]}`).join(" "),
    wrong: wrongAt.map((i) => passage.chars[i]).join(" "),
  };
}

// ── 한 문항의 답 기록 (과제 화면이 만들고, 실험 진행 화면과 spike가 각자 저장) ──
export type AnswerRow = {
  shownMs: number; // 문항이 보인 시각 (과제 시작 기준 경과 ms)
  answeredMs: number; // 답한 시각 (과제 시작 기준 경과 ms)
  problem: string; // 계산: "34+58" / 오탈자: 지문 번호
  answer: string; // 계산: 정답 / 오탈자: 오타 글자 수
  input: string; // 계산: 입력값 / 오탈자: 누른 글자 수
  correct: boolean; // 계산: 정답 여부 / 오탈자: 오타를 다 찾고 잘못 누른 것이 없음
  detail: string; // 계산: "받아올림" 여부 / 오탈자: "맞힘/놓침/잘못" 수
  missed: string; // 오탈자: 놓친 오타 "원문→오타" (계산은 빈칸)
  wrong: string; // 오탈자: 잘못 누른 글자 (계산은 빈칸)
};

// ── 실험 기록: 조건마다 한 파일 (docs/사용자-실험-재설계.md 6절 "과제 입력 기록") ──
export type TaskRow = AnswerRow & {
  participant: string;
  condition: string; // A/B/C
  order: string; // 그 참가자의 조건 순서
  kind: Candidate;
  set: number; // 문제 세트 번호(1~3). 계산은 시드만 다르고 세트 번호는 기록용
  seed: number;
  index: number; // 몇 번째 문항
  answeredAt: string; // ISO (지역 시차 포함)
};

export const TASK_CSV_HEADER = [
  "participant", "condition", "order", "kind", "set", "seed", "index", "shown_ms", "answered_ms", "elapsed_ms",
  "problem", "answer", "input", "correct", "detail", "missed", "wrong", "answered_at",
];

const taskCell = (v: string | number | boolean) => {
  const s = String(v);
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

export function taskCsv(rows: TaskRow[]): string {
  const body = rows.map((r) =>
    [
      r.participant, r.condition, r.order, r.kind, r.set, r.seed, r.index, r.shownMs, r.answeredMs, r.answeredMs - r.shownMs,
      r.problem, r.answer, r.input, r.correct ? 1 : 0, r.detail, r.missed, r.wrong, r.answeredAt,
    ].map(taskCell).join(","),
  );
  return [TASK_CSV_HEADER.join(","), ...body].join("\n");
}

// 분당 맞힌 수 (주 지표). 오탈자는 맞게 찾은 오타 수를 셉니다.
export function correctCount(rows: AnswerRow[], kind: Candidate): number {
  return kind === "calc" ? rows.filter((r) => r.correct).length : rows.reduce((s, r) => s + Number(r.detail.split("/")[0] || 0), 0);
}
