export const CALC_MIN = 10; // 계산 과제 피연산자 범위: 두 자리 수
export const CALC_MAX = 99;
export const CARRY_RATIO = 0.5; // 받아올림이 있는 문제 비율 (난이도를 세트마다 같게 하려는 규칙)

export type Candidate = "calc" | "typo";
