-- 두뜀 0058: 캠빛 해변 — 비치체어에서 공부하기 (24석)
-- 실행 위치: Supabase 대시보드 > SQL Editor (서비스 프로젝트. develop 전용이며 실험 프로젝트에서는 실행하지 않는다)
-- 0014(카페 지점 종류 kind)를 먼저 실행해 두어야 한다.
--
-- 배경:
--   세 번째 바깥 공간 /beach 의 비치체어에 앉아 벤치(0038)·빈백(0043)과 똑같이 공부(타이머·집중 판정·기록 저장)한다.
--   공부 기록은 좌석 이용 기록에 붙어야 하므로 해변을 카페(kind 'cafe') 지점 'beach' 로 등록하고 비치체어를 그 지점의 좌석으로 둔다.
--   빈자리에 앉으면 내 자리, 일어나면 놓음(sit_cafe_seat·leave_cafe_seat 그대로). DB 함수는 바꾸지 않는다.
--   is_open 은 false: 해변은 건물이 아니라서 열린 지점 목록에 들어가지 않게 한다(0038 광장과 같음).
--
-- 좌석 번호와 좌표:
--   src/world/beachLogic.ts 의 beachSeats 와 같다(beach.json 의 줄·칸 순서). 화면은 JSON 에서 계산하므로 여기 좌표는 참고용이다.
--   방향(rot)은 앉은 사람이 보는 쪽(바다, -z).
--
-- 권한: 새 표가 없어 RLS 변경이 없다. 지점·좌석은 기존 정책을 따른다.
--
-- 다시 실행하기: 지점은 slug 가 이미 있으면 건너뛰고, 좌석은 번호가 이미 있으면 건너뛴다. 몇 번 실행해도 된다.

begin;

insert into public.branches (name, slug, kind, is_open)
values ('캠빛 해변', 'beach', 'cafe', false)
on conflict (slug) do nothing;

insert into public.seats (branch_id, seat_number, pos_x, pos_z, rot)
select b.id, v.seat_number, v.pos_x, v.pos_z, v.rot
from public.branches b
cross join (values
  (1, -20.7, -5.0, 3.142),
  (2, -19.3, -5.0, 3.142),
  (3, -12.7, -5.0, 3.142),
  (4, -11.3, -5.0, 3.142),
  (5, -4.7, -5.0, 3.142),
  (6, -3.3, -5.0, 3.142),
  (7, 3.3, -5.0, 3.142),
  (8, 4.7, -5.0, 3.142),
  (9, 11.3, -5.0, 3.142),
  (10, 12.7, -5.0, 3.142),
  (11, 19.3, -5.0, 3.142),
  (12, 20.7, -5.0, 3.142),
  (13, -20.7, 0.0, 3.142),
  (14, -19.3, 0.0, 3.142),
  (15, -12.7, 0.0, 3.142),
  (16, -11.3, 0.0, 3.142),
  (17, -4.7, 0.0, 3.142),
  (18, -3.3, 0.0, 3.142),
  (19, 3.3, 0.0, 3.142),
  (20, 4.7, 0.0, 3.142),
  (21, 11.3, 0.0, 3.142),
  (22, 12.7, 0.0, 3.142),
  (23, 19.3, 0.0, 3.142),
  (24, 20.7, 0.0, 3.142)
) as v(seat_number, pos_x, pos_z, rot)
where b.slug = 'beach'
on conflict (branch_id, seat_number) do nothing;

commit;
